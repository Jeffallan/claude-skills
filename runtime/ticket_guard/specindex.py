"""`guard spec-index`: docs/specs/INDEX.md from the overview header lines; never edited by hand."""

from __future__ import annotations

from dataclasses import dataclass, field
from pathlib import Path
import re

from ticket_guard import settings
from ticket_guard.gitutil import top

HEADER = re.compile(r"^(?:\*\*)?(Spec|Discovery|After|Feature areas):(?:\*\*)?\s*(.*)$")
EMPTY = {"", "-", "none", "n/a"}
FOLDERS = ("todo", "completed")
DISCOVERY = "discovery"  # <specsRoot>/<status>/discovery/<topic>/


def _dirs(base: Path) -> list[Path]:
    return sorted(p for p in base.iterdir() if p.is_dir()) if base.is_dir() else []


@dataclass
class Spec:
    name: str
    status: str
    fields: dict[str, list[str]] = field(default_factory=dict)


def _headers(text: str) -> dict[str, list[str]]:
    """Header lines above the first `## ` heading."""
    out: dict[str, list[str]] = {}
    for line in text.splitlines():
        if line.startswith("## "):
            break
        match = HEADER.match(line.strip())
        if match:
            values = [v.strip() for v in match.group(2).split(",")]
            out[match.group(1)] = [v for v in values if v.lower() not in EMPTY]
    return out


def scan(root: Path) -> tuple[list[Spec], set[str], list[str], list[str]]:
    """(specs, discovery topics, errors, warnings) under `root`'s todo/ and completed/ folders."""
    specs, topics, errors, warnings = [], set(), [], []
    for status in FOLDERS:
        base = root / status
        topics |= {p.name for p in _dirs(base / DISCOVERY)}
        for folder in _dirs(base):
            if folder.name == DISCOVERY:
                continue
            overview = folder / "overview.md"
            if not overview.is_file():
                warnings.append(
                    f"{folder.name}: no overview.md in {status}/{folder.name} "
                    f"(discovery topics go under {status}/{DISCOVERY}/)"
                )
                continue
            fields = _headers(overview.read_text(encoding="utf-8"))
            specs.append(Spec(folder.name, status, fields))
            named = fields.get("Spec")
            if not named:
                errors.append(f"{folder.name}: no Spec: line in {status}/{folder.name}/overview.md")
            elif named != [folder.name]:
                errors.append(f"{folder.name}: Spec: line says {', '.join(named)}, folder is {folder.name}")
    names = {s.name for s in specs}
    for spec in specs:
        errors += [f"{spec.name}: After: {n} is not a spec" for n in spec.fields.get("After", []) if n not in names]
        errors += [
            f"{spec.name}: Discovery: {n} is not a discovery topic"
            for n in spec.fields.get("Discovery", [])
            if n not in topics
        ]
    return sorted(specs, key=lambda s: s.name), topics, errors, warnings


def render(specs: list[Spec]) -> str:
    lines = [
        "# Spec index",
        "",
        (
            "Generated by `guard spec-index` from each overview's `Spec:`, `Discovery:`, "
            "`After:` and `Feature areas:` lines. Do not edit by hand; `--check` fails when it is stale."
        ),
        "",
        "| Spec | Status | Discovery | Feature areas | After |",
        "|------|--------|-----------|---------------|-------|",
    ]
    for s in specs:
        cols = [", ".join(s.fields.get(k, [])) or "-" for k in ("Discovery", "Feature areas", "After")]
        lines.append(f"| [{s.name}]({s.status}/{s.name}/) | {s.status} | " + " | ".join(cols) + " |")
    return "\n".join(lines) + "\n"


def build(cwd: Path, check: bool = False) -> tuple[Path, list[str], list[str]]:
    """Write (or with check, compare) INDEX.md; returns its path, the errors and the warnings."""
    root = top(cwd) / settings.get(cwd, "specsRoot")
    specs, _, errors, warnings = scan(root)
    path = root / "INDEX.md"
    text = render(specs)
    if check:
        current = path.read_text(encoding="utf-8") if path.is_file() else None
        if current != text:
            errors.append(f"{path} is stale; run `guard spec-index`")
    else:
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(text, encoding="utf-8")
    return path, errors, warnings

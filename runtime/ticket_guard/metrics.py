"""`guard metrics`: clone, dead-code and complexity reports on the spec diff, from whatever tools exist."""

from __future__ import annotations

from pathlib import Path
import shutil
import subprocess

from ticket_guard import settings
from ticket_guard.gitutil import git, top

CODE = (
    ".py",
    ".js",
    ".jsx",
    ".ts",
    ".tsx",
    ".mjs",
    ".cjs",
    ".go",
    ".rb",
    ".java",
    ".kt",
    ".rs",
    ".cs",
    ".php",
    ".swift",
    ".c",
    ".cpp",
    ".h",
)
JS = (".js", ".jsx", ".ts", ".tsx", ".mjs", ".cjs")
# name -> (what it finds, which changed files it takes, argv before the files, install hint)
TOOLS: dict[str, tuple[str, tuple[str, ...], list[str], str]] = {
    "jscpd": (
        "duplicated code",
        CODE,
        ["--silent", "--reporters", "console"],
        "npm i -g jscpd",
    ),
    "knip": (
        "unused files, exports and dependencies (JS/TS project)",
        JS,
        ["--no-progress"],
        "npm i -D knip",
    ),
    "vulture": ("dead Python code", (".py",), [], "uv tool install vulture"),
    "lizard": ("cyclomatic complexity", CODE, [], "uv tool install lizard"),
}
MAX_LINES = 200


def default_base(cwd: Path) -> str:
    for ref in ("origin/HEAD", "main", "master"):
        if git(cwd, "rev-parse", "--verify", "-q", ref, check=False):
            return git(cwd, "merge-base", "HEAD", ref)
    return git(cwd, "rev-list", "--max-parents=0", "HEAD").splitlines()[0]


def report(cwd: Path, spec: str, base: str | None = None) -> Path:
    root = top(cwd)
    base = base or default_base(cwd)
    changed = [
        p
        for p in git(cwd, "diff", "--name-only", "--diff-filter=AMR", base, "HEAD").splitlines()
        if p and (root / p).is_file()
    ]
    lines = [
        f"# Metrics for {spec}",
        "",
        f"Base `{base[:12]}`, HEAD `{git(cwd, 'rev-parse', 'HEAD')[:12]}`. Generated by `guard metrics`.",
        "",
        "Changed files: " + (", ".join(f"`{p}`" for p in changed) or "none"),
        "",
    ]
    for name, (finds, exts, argv, hint) in TOOLS.items():
        lines.append(f"## {name} ({finds})")
        lines.append("")
        targets = [p for p in changed if p.endswith(exts)]
        exe = shutil.which(name) if targets else None
        if not targets:  # checked first, so a Python tool is never suggested for a TypeScript diff
            lines.append(f"{name}: no changed files it reads.")
        elif exe is None:
            lines.append(f"{name}: not installed, so this check did not run (install: `{hint}`).")
        else:
            args = [exe, *argv] if name == "knip" else [exe, *argv, *targets]
            proc = subprocess.run(args, cwd=root, capture_output=True, text=True, check=False)
            out = (proc.stdout + proc.stderr).strip().splitlines()
            lines.append(f"`{name}` exit {proc.returncode}:")
            lines += ["", "```text", *out[:MAX_LINES], "```"]
            if len(out) > MAX_LINES:
                lines.append(f"({len(out) - MAX_LINES} more lines cut)")
        lines.append("")
    path = settings.spec_dir(cwd, spec) / "review" / "metrics.md"
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text("\n".join(lines), encoding="utf-8")
    return path

from ticket_guard.__main__ import main

ROOT = "docs/specs"


def overview(git_repo, where, name, discovery="none", after="none", areas="cli", spec=None):
    git_repo.write(
        f"{ROOT}/{where}/{name}/overview.md",
        f"# {name}\n\n**Spec:** {spec or name}\n**Discovery:** {discovery}\n"
        f"**After:** {after}\n**Feature areas:** {areas}\n\n## Summary\n\nSpec: not a header\n",
    )


def topic(git_repo, where, name):
    git_repo.write(f"{ROOT}/{where}/discovery/{name}/notes.md", "# notes\n")


def setup(git_repo):
    topic(git_repo, "completed", "auth-topic")
    topic(git_repo, "todo", "billing-topic")
    overview(git_repo, "completed", "login", discovery="auth-topic", areas="auth, sessions")
    overview(git_repo, "todo", "demo", discovery="auth-topic, billing-topic", after="login")


def index(git_repo):
    return (git_repo.root / ROOT / "INDEX.md").read_text()


def test_generates_the_index_from_overview_headers(git_repo, capsys):
    setup(git_repo)
    assert main(["spec-index"]) == 0
    text = index(git_repo)
    assert "Generated by `guard spec-index`" in text
    lines = [x for x in text.splitlines() if x.startswith("| [")]
    assert lines == [
        "| [demo](todo/demo/) | todo | auth-topic, billing-topic | cli | login |",
        "| [login](completed/login/) | completed | auth-topic | auth, sessions | - |",
    ]


def test_check_passes_when_current_and_fails_when_stale(git_repo, capsys):
    setup(git_repo)
    main(["spec-index"])
    assert main(["spec-index", "--check"]) == 0
    overview(git_repo, "todo", "next", after="demo")
    assert main(["spec-index", "--check"]) == 1
    assert "stale" in capsys.readouterr().err
    (git_repo.root / ROOT / "INDEX.md").unlink()
    assert main(["spec-index", "--check"]) == 1


def test_check_fails_on_broken_name_links(git_repo, capsys):
    setup(git_repo)
    overview(git_repo, "todo", "bad", discovery="no-such-topic", after="ghost")
    overview(git_repo, "todo", "renamed", spec="old-name")
    assert main(["spec-index"]) == 1
    err = capsys.readouterr().err
    assert "bad: After: ghost is not a spec" in err
    assert "bad: Discovery: no-such-topic is not a discovery topic" in err
    assert "renamed: Spec: line says old-name" in err
    assert main(["spec-index", "--check"]) == 1


def test_missing_spec_line_is_an_error(git_repo, capsys):
    git_repo.write(f"{ROOT}/todo/plain/overview.md", "# Plain\n\nNo header.\n")
    assert main(["spec-index"]) == 1
    assert "plain: no Spec: line" in capsys.readouterr().err


def test_specs_root_comes_from_config(git_repo, capsys):
    git_repo.write(".claude/workflow-config.json", '{"specsRoot": "specs"}')
    git_repo.write("specs/todo/x/overview.md", "**Spec:** x\n")
    assert main(["spec-index"]) == 0
    assert "[x](todo/x/)" in (git_repo.root / "specs/INDEX.md").read_text()


def test_discovery_folder_is_never_a_spec_and_old_topic_folders_warn(git_repo, capsys):
    setup(git_repo)
    git_repo.write(f"{ROOT}/todo/old-topic/notes.md", "# notes\n")
    assert main(["spec-index"]) == 0
    err = capsys.readouterr().err
    assert "warning: old-topic: no overview.md in todo/old-topic" in err
    assert "/discovery/" not in index(git_repo)
    assert "old-topic" not in index(git_repo)
    assert main(["spec-index", "--check"]) == 0


def test_a_name_resolving_only_to_an_old_topic_folder_is_still_an_error(git_repo, capsys):
    setup(git_repo)
    git_repo.write(f"{ROOT}/todo/old-topic/notes.md", "# notes\n")
    overview(git_repo, "todo", "late", discovery="old-topic")
    assert main(["spec-index"]) == 1
    assert "late: Discovery: old-topic is not a discovery topic" in capsys.readouterr().err
